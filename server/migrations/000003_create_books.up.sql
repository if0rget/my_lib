CREATE TABLE IF NOT EXISTS books (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(200) NOT NULL,
  author VARCHAR(100) NOT NULL,
  isbn VARCHAR(20) NOT NULL,
  category_id BIGINT NOT NULL REFERENCES categories(id),
  publisher VARCHAR(100) NOT NULL DEFAULT '',
  published_year INT NOT NULL DEFAULT 0,
  total_stock INT NOT NULL CHECK (total_stock >= 0),
  available_stock INT NOT NULL CHECK (available_stock >= 0 AND available_stock <= total_stock),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  deleted_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX books_isbn_key ON books (isbn) WHERE deleted_at IS NULL;
CREATE INDEX books_category_id_idx ON books (category_id);
